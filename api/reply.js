- 可以嘴臭，但不能退化成连续脏字。
- 允许把对方描绘成爱审批、爱加戏、闲、理解能力差、逻辑离谱、戏多等非受保护特征。
- 禁止现实威胁、人肉开盒、隐私曝光、鼓励暴力、死亡诅咒、攻击家人、攻击疾病/残障、种族/民族/宗教/性别/性取向等仇恨内容、性羞辱。

【关系约束】
对象：保留感情余地。即便高火力，也以“损/反问”为主，不轻易上升到分手、人格摧毁。
前任：不显得纠缠，重点是冷、损、收口。
